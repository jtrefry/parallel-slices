test("applies the exact Mantine baseline and removes Tailwind", () => {
  const root = mkdtempSync(join(tmpdir(), "parallel-slices-mantine-"));
  try {
    writeScaffold(root, {
      foundationDependencies: false,
      nextApps: true,
    });
    const docsPackagePath = join(root, "apps/docs/package.json");
    const docsPackageBefore = JSON.parse(readFileSync(docsPackagePath, "utf8"));
    docsPackageBefore.dependencies["@repo/ui"] = "*";
    writeFileSync(
      docsPackagePath,
      `${JSON.stringify(docsPackageBefore, null, 2)}\n`,
    );
    const baseline = loadScaffoldBaseline();
    const profile = configureScaffold(root, {
      createTurboVersion: "2.10.5",
      manager: "npm",
    });
    const webPackage = JSON.parse(
      readFileSync(join(root, "apps/web/package.json"), "utf8"),
    );
    const uiPackage = JSON.parse(
      readFileSync(join(root, "packages/ui/package.json"), "utf8"),
    );
    const rootPackage = JSON.parse(
      readFileSync(join(root, "package.json"), "utf8"),
    );
    const eslintPackage = JSON.parse(
      readFileSync(join(root, "packages/eslint-config/package.json"), "utf8"),
    );
    const readme = readFileSync(join(root, "README.md"), "utf8");

    assert.equal(profile.framework.version, baseline.dependencies.next);
    assert.equal(profile.ui.version, baseline.dependencies["@mantine/core"]);
    assert.equal(profile.schemaVersion, 4);
    assert.equal(profile.dataLayer, "postgres");
    assert.deepEqual(profile.node, baseline.parallelSlices.node);
    assert.deepEqual(profile.applications, ["apps/web"]);
    assert.equal(existsSync(join(root, "apps/docs")), false);
    assert.equal(webPackage.dependencies.react, baseline.dependencies.react);
    assert.equal(docsPackageBefore.dependencies["@repo/ui"], "*");
    assert.equal(
      webPackage.devDependencies["postcss-preset-mantine"],
      baseline.devDependencies["postcss-preset-mantine"],
    );
    assert.equal(uiPackage.dependencies["@mantine/core"], profile.ui.version);
    assert.equal(
      rootPackage.packageManager,
      `npm@${baseline.parallelSlices.packageManagers.npm}`,
    );
    assert.deepEqual(profile.review, { cursorProvider: "cursor-agent" });
    assert.equal(rootPackage.devDependencies["@cursor/sdk"], undefined);
    assert.equal(
      rootPackage.engines.node,
      baseline.parallelSlices.node.engines,
    );
    assert.equal(
      readFileSync(join(root, ".node-version"), "utf8"),
      `${baseline.parallelSlices.node.pin}\n`,
    );
    for (const name of ["husky", "prettier", "turbo", "typescript"]) {
      assert.equal(
        rootPackage.devDependencies[name],
        baseline.devDependencies[name],
      );
    }
    for (const name of [
      "@eslint/js",
      "eslint",
      "eslint-config-prettier",
      "eslint-plugin-only-warn",
      "eslint-plugin-react",
      "eslint-plugin-react-hooks",
      "eslint-plugin-turbo",
      "globals",
      "typescript-eslint",
    ]) {
      assert.equal(
        eslintPackage.devDependencies[name],
        baseline.devDependencies[name],
      );
    }
    assert.equal(
      rootPackage.overrides.postcss,
      baseline.devDependencies.postcss,
    );
    assert.doesNotMatch(
      readFileSync(join(root, "apps/web/app/globals.css"), "utf8"),
      /tailwind/i,
    );
    assert.match(readme, /Default controller: `Cursor`/);
    assert.match(readme, /Architecture: `nextjs-gcp-postgres`/);
    assert.match(readme, /\.parallel-slices\/architecture\.json/);
    assert.match(readme, /This starter project was generated by/);
    assert.match(
      readme,
      /github\.com\/jtrefry\/parallel-slices\/blob\/main\/docs\/mechanism-map\.md/,
    );
    assert.match(
      readme,
      /github\.com\/jtrefry\/parallel-slices\/blob\/main\/docs\/pipeline-walkthrough\.md/,
    );
    assert.match(readme, /docs\/parallel-slices\/using-codex\.md/);
    assert.match(readme, /docs\/parallel-slices\/using-cursor\.md/);
    assert.match(readme, /docs\/parallel-slices\/using-claude-code\.md/);
    assert.match(readme, /Node\.js 22 LTS or 24 LTS/);
    assert.match(
      readme,
      /review provider only when multi-agent review is enabled/,
    );
    assert.match(
      readme,
      /Multi-agent planning and integrated slice\/code review is optional/,
    );
    assert.match(readme, /"enabled": false/);
    assert.ok(
      readme.indexOf('"enabled": false') <
        readme.indexOf("## Understand the complete workflow"),
    );
    assert.match(readme, /Docker Desktop/);
    assert.doesNotMatch(readme, /## What the workflow does/);
    assert.match(readme, /`apps\/web\/` is the starter Next\.js application/);
    assert.match(readme, /`docs\/` is the root for repository documentation/);
    assert.doesNotMatch(readme, /apps\/docs/);
    assert.match(readme, /npm ci/);
    assert.doesNotMatch(readme, /create-turbo@latest/);
    assert.deepEqual(verifyScaffoldProfile(root), {
      applications: ["apps/web"],
      status: "verified",
    });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

