test("renders clone onboarding for every supported package manager", () => {
  const baseline = loadScaffoldBaseline();
  const expectedCommands = {
    npm: ["npm ci", "npm run build"],
    pnpm: [
      "corepack-runner.mjs pnpm install --frozen-lockfile",
      "corepack-runner.mjs pnpm run build",
    ],
    yarn: [
      "corepack-runner.mjs yarn install --immutable",
      "corepack-runner.mjs yarn run build",
    ],
    bun: ["bun install --frozen-lockfile", "bun run build"],
  };

  for (const [manager, commands] of Object.entries(expectedCommands)) {
    const root = mkdtempSync(
      join(tmpdir(), `parallel-slices-${manager}-readme-`),
    );
    try {
      writeScaffold(root, {
        foundationDependencies: false,
        manager,
        nextApps: true,
      });
      configureScaffold(root, {
        createTurboVersion: "2.10.5",
        manager,
      });
      const readme = readFileSync(join(root, "README.md"), "utf8");
      const rootPackage = JSON.parse(
        readFileSync(join(root, "package.json"), "utf8"),
      );
      for (const command of commands) assert.ok(readme.includes(command));
      assert.doesNotMatch(readme, /{{[A-Z_]+}}/);
      assert.equal(
        rootPackage.packageManager,
        `${manager}@${baseline.parallelSlices.packageManagers[manager]}`,
      );
      assert.equal(verifyScaffoldProfile(root).status, "verified");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }
});

test("generated Dependabot updates stay dormant until initialization", () => {
  const config = parseYaml(
    readFileSync(
      join(
        import.meta.dirname,
        "../architectures/nextjs-gcp-postgres/repo-overlay/.github/dependabot.yml",
      ),
      "utf8",
    ),
  );
  assert.deepEqual(
    config.updates.map((update) => update["package-ecosystem"]),
    ["npm", "github-actions"],
  );
  assert.ok(
    config.updates.every((update) => update["open-pull-requests-limit"] === 0),
  );
  assert.deepEqual(
    config.updates[0].ignore.map((entry) => entry["dependency-name"]).sort(),
    ["@eslint/js", "@types/node", "eslint", "typescript"],
  );
});

